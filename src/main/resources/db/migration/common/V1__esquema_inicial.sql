-- Esquema inicial del backend de procesos BPMN (generado a partir de las entidades JPA).
-- Una migracion aplicada no se edita: los cambios nuevos van en un archivo V<n> posterior.

    create table arcos (
        activo boolean not null,
        destino_id bigint not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        origen_id bigint not null,
        pool_id bigint not null,
        condicion varchar(255),
        etiqueta varchar(255),
        primary key (id)
    );

    create table correlaciones (
        activo boolean not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        mensaje_id bigint not null,
        criterio varchar(255) not null,
        primary key (id)
    );

    create table empresas (
        fecha_registro date not null,
        id bigint generated by default as identity,
        correo_contacto varchar(255) not null,
        nit varchar(255) not null unique,
        nombre varchar(255) not null,
        primary key (id)
    );

    create table historial_cambios (
        autor_id bigint not null,
        empresa_id bigint not null,
        fecha_cambio timestamp(6) not null,
        id bigint generated by default as identity,
        proceso_id bigint not null,
        descripcion_cambio varchar(255) not null,
        primary key (id)
    );

    create table invitaciones_usuario (
        usada boolean not null,
        empresa_id bigint not null,
        fecha_expiracion timestamp(6) not null,
        id bigint generated by default as identity,
        email varchar(255) not null,
        rol_acceso varchar(255) not null check ((rol_acceso in ('ADMINISTRADOR','EDITOR','SOLO_LECTURA'))),
        token varchar(255) not null unique,
        primary key (id)
    );

    create table lanes (
        activo boolean not null,
        orden integer not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        pool_id bigint not null,
        rol_proceso_id bigint not null,
        nombre varchar(255) not null,
        primary key (id)
    );

    create table mensajes (
        activo boolean not null,
        actividad_error_id bigint,
        empresa_id bigint not null,
        evento_catch_id bigint,
        evento_throw_id bigint,
        id bigint generated by default as identity,
        pool_destino_id bigint not null,
        pool_origen_id bigint not null,
        proceso_id bigint not null,
        clave_correlacion varchar(255),
        contenido text not null,
        destino_externo varchar(255),
        nombre varchar(255) not null,
        politica_fallo_notificacion varchar(255) check ((politica_fallo_notificacion in ('CONTINUAR_FLUJO','DERIVAR_ACTIVIDAD_ERROR','FINALIZAR_PROCESO'))),
        politica_sin_caso varchar(255) check ((politica_sin_caso in ('DESCARTAR','INICIAR_CASO_NUEVO'))),
        tipo_destino_externo varchar(255) check ((tipo_destino_externo in ('CORREO','SERVICIO_WEB','COLA'))),
        primary key (id)
    );

    create table nodos_flujo (
        activo boolean not null,
        origen_externo boolean,
        posicion_x integer not null,
        posicion_y integer not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        lane_id bigint not null,
        tipo_nodo varchar(31) not null check ((tipo_nodo in ('ACTIVIDAD','EVENTO_MENSAJE','GATEWAY'))),
        clave_correlacion_evento varchar(255),
        contenido_evento text,
        descripcion varchar(255),
        nombre varchar(255) not null,
        tipo_actividad varchar(255) check ((tipo_actividad in ('TAREA','USUARIO','SERVICIO','MANUAL','SCRIPT','REGLA_NEGOCIO'))),
        tipo_evento_mensaje varchar(255) check ((tipo_evento_mensaje in ('THROW','CATCH_INICIO','CATCH_INTERMEDIO'))),
        tipo_gateway varchar(255) check ((tipo_gateway in ('EXCLUSIVO','PARALELO','INCLUSIVO'))),
        primary key (id),
        check (tipo_nodo <> 'EVENTO_MENSAJE' or (origen_externo is not null))
    );

    create table permisos_estructura (
        crear_lane boolean not null,
        crear_pool boolean not null,
        editar_lane boolean not null,
        editar_pool boolean not null,
        eliminar_lane boolean not null,
        eliminar_pool boolean not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        rol_acceso varchar(255) not null check ((rol_acceso in ('ADMINISTRADOR','EDITOR','SOLO_LECTURA'))),
        primary key (id),
        unique (empresa_id, rol_acceso)
    );

    create table pools (
        activo boolean not null,
        caja_negra boolean not null,
        orden integer not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        proceso_id bigint not null,
        nombre varchar(255) not null,
        tipo_participante varchar(255) not null check ((tipo_participante in ('EMPRESA','CLIENTE','PROVEEDOR','SISTEMA_EXTERNO'))),
        primary key (id)
    );

    create table procesos (
        activo boolean not null,
        empresa_id bigint not null,
        fecha_creacion timestamp(6) not null,
        fecha_modificacion timestamp(6) not null,
        id bigint generated by default as identity,
        categoria varchar(255) not null,
        descripcion text not null,
        estado varchar(255) not null check ((estado in ('BORRADOR','PUBLICADO'))),
        nombre varchar(255) not null,
        primary key (id)
    );

    create table procesos_compartidos (
        activo boolean not null,
        solo_lectura boolean not null,
        empresa_id bigint not null,
        empresa_invitada_id bigint not null,
        id bigint generated by default as identity,
        proceso_id bigint not null,
        primary key (id),
        unique (proceso_id, empresa_invitada_id)
    );

    create table roles_proceso (
        activo boolean not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        descripcion varchar(255),
        nombre varchar(255) not null,
        primary key (id)
    );

    create table usuarios (
        activo boolean not null,
        empresa_id bigint not null,
        id bigint generated by default as identity,
        email varchar(255) not null unique,
        nombre varchar(255) not null,
        password_hash varchar(255) not null,
        rol_acceso varchar(255) not null check ((rol_acceso in ('ADMINISTRADOR','EDITOR','SOLO_LECTURA'))),
        primary key (id)
    );

